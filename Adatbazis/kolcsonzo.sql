CREATE TABLE kliens(
    id INTEGER PRIMARY KEY AUTO_INCREMENT,
    nev VARCHAR(100),
    szido DATE,
    telszam VARCHAR(12));
	
CREATE TABLE auto(
    id INTEGER PRIMARY KEY AUTO_INCREMENT,
    marka VARCHAR(20),
    tipus VARCHAR(50),
    evjarat INTEGER,
    szin VARCHAR(20),
    teljesitmeny INTEGER);
	
CREATE TABLE kolcsonzes(
    kliens_id INTEGER,
    auto_id INTEGER,
    mettol DATE,
    meddig DATE,
    ar INTEGER,
    PRIMARY KEY(kliens_id, auto_id),
    FOREIGN KEY(kliens_id) REFERENCES kliens(id),
    FOREIGN KEY(auto_id) REFERENCES auto(id));
	
